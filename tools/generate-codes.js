// Generates personal entry codes for "codes" access mode.
//   node tools/generate-codes.js [count]
// Writes access-codes.js (hashes only — safe to publish) and private/codes.csv (the real codes — NEVER commit).
const crypto = require("crypto");
const fs = require("fs");
const path = require("path");

const SALT = "ashrf-remas-tours-v1";
const ITER = 150000;
const ALPHABET = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789";
const count = parseInt(process.argv[2] || "200", 10);

const rand = (n) => Array.from(crypto.randomBytes(n), (b) => ALPHABET[b % 32]).join("");
const normalize = (c) => c.toUpperCase().replace(/[^A-Z0-9]/g, "").replace(/^ASHRF/, "");
const hash = (c) => crypto.pbkdf2Sync(normalize(c), SALT, ITER, 32, "sha256").toString("hex");
const make = () => `ASHRF-${rand(4)}-${rand(4)}`;

const codes = Array.from({ length: count }, make);
const admin = `ASHRF-${rand(4)}-${rand(4)}`;

const out = `// Generated by tools/generate-codes.js — hashes only, the codes themselves are not here.
// To block a customer's code, replace its line with null (the list number is in the private codes file).
window.ACCESS_CODES = {
  salt: ${JSON.stringify(SALT)},
  iterations: ${ITER},
  admin: [${JSON.stringify(hash(admin))}],
  customers: [
${codes.map((c, i) => `    ${JSON.stringify(hash(c))}, // #${i + 1}`).join("\n")}
  ],
};
`;
fs.writeFileSync(path.join(__dirname, "..", "access-codes.js"), out);

const privDir = process.env.CODES_OUT || path.join(__dirname, "..", "private");
fs.mkdirSync(privDir, { recursive: true });
const csv = "number,code,customer name,phone,paid,date\n" +
  `ADMIN,${admin},Ashraf (owner),,,\n` +
  codes.map((c, i) => `${i + 1},${c},,,,`).join("\n") + "\n";
fs.writeFileSync(path.join(privDir, "codes.csv"), "﻿" + csv);
console.log(`admin: ${admin}\n${count} codes written to ${privDir}/codes.csv`);
